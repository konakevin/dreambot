const blocks = require('../../pixelbot/shared-blocks');

const DUNGEON_ROOMS = require('../seeds/pixel_haunted_dungeon_room.json');
const TORCH_WALLS = require('../seeds/pixel_haunted_dungeon_torchwall.json');
const HAUNTED_ENEMIES = require('../seeds/pixel_haunted_dungeon_enemy.json');
const FLOOR_DETAILS = require('../seeds/pixel_haunted_dungeon_floor.json');

// Short fixed lists — no generated-pool variety needed, per playbook guidance.
const BACKGROUND_GLIMPSES = [
  'a barred stone window high on the back wall glowing with a sliver of pale moonlight',
  'a shadowed archway leading deeper into an unseen corridor',
  'a crumbling stairwell disappearing upward out of frame',
  'a heavy iron portcullis half-raised at the room’s far edge',
  'a cracked stone door standing slightly ajar onto darkness beyond',
  'a faint glow flickering from a corridor just out of view',
  'a low tunnel opening at floor level leading further underground',
  'a broken wooden ladder leaning against a gap in the back wall',
];

const ATMOSPHERIC_FLOURISHES = [
  'a few bats flutter near the ceiling, wings catching the torchlight',
  'loose dust motes drift lazily through a torchlit shaft of air',
  'a stray cobweb sways gently in an unseen draft',
  'a small rat scurries along the floor’s edge',
  'a loose stone ticks and settles somewhere unseen',
  'a faint echo of dripping water sounds from somewhere deeper',
  'a tiny floating orb of pale witch-light drifts lazily near the ceiling, a smooth glowing speck of ambient radiance',
  'a curl of torch-smoke drifts upward past the ceiling beams',
];

module.exports = ({ sharedDNA, vibeDirective, picker }) => {
  const room = picker.pickWithRecency(DUNGEON_ROOMS, 'pixel_haunted_dungeon_room');
  const wall = picker.pickWithRecency(TORCH_WALLS, 'pixel_haunted_dungeon_torchwall');
  const enemy = picker.pickWithRecency(HAUNTED_ENEMIES, 'pixel_haunted_dungeon_enemy');
  const floor = picker.pickWithRecency(FLOOR_DETAILS, 'pixel_haunted_dungeon_floor');
  const background = picker.pickWithRecency(
    BACKGROUND_GLIMPSES,
    'pixel_haunted_dungeon_background'
  );

  // Atmospheric flourish stays OPTIONAL (~50%) — per the hard-won lesson
  // that a signature detail mandatory on every entry homogenizes every
  // render into "the same one thing."
  let flourishBlock = '';
  if (Math.random() < 0.5) {
    const flourish = picker.pickWithRecency(
      ATMOSPHERIC_FLOURISHES,
      'pixel_haunted_dungeon_flourish'
    );
    flourishBlock = `\n━━━ AN ATMOSPHERIC FLOURISH (one small extra motion detail) ━━━\n${flourish}\n`;
  }

  return `You are a 16-bit pixel-art game artist writing a SIDE-VIEW HAUNTED-DUNGEON-ROOM gameplay screenshot for a Halloween candidate pixel-art bot path. A classic 2D side-view RPG dungeon interior — a flat cross-section straight into a torch-lit stone chamber, the enemy-encounter screen you'd see stepping into a haunted crypt room. Family-friendly spooky-cute Halloween: playful and charming, never genuine horror or gore.

━━━ THE HAUNTED DUNGEON ROOM — NON-NEGOTIABLE TEMPLATE MANDATE ━━━
The camera is ALWAYS a flat SIDE-VIEW cross-section into the room (like a classic 2D side-view RPG/platformer dungeon screen) — NEVER top-down, NEVER 3/4-isometric, NEVER an outdoor establishing shot. The room is a torch-lit stone-walled dungeon chamber holding exactly ONE ghost-or-skeleton enemy sprite, rendered mid-idle-action like a paused game moment. The enemy is PLAYFUL and cheeky — a friendly game-mascot monster, never a genuine scare.

━━━ THE ROOM (side-view layout) ━━━
${room}

━━━ THE TORCH-LIT WALL — THE MONEY SHOT (warm flickering firelight against cold stone) ━━━
${wall}
This wall must also carry ONE small distinctive decorative anchor beyond the torches themselves — a carved bust, a mounted relic, a hanging chain, a tattered banner, a trophy skull, an old weapon, a rusted manacle — so the shot reads as a SPECIFIC memorable place, never just generic firelight on bare stone.

━━━ THE HAUNTED ENEMY (exactly one, mid-idle-action, PLAYFUL not scary) ━━━
${enemy}

━━━ THE FLOOR ━━━
${floor}

━━━ GLIMPSED BEYOND THE ROOM (reinforces the side-view camera) ━━━
${background}
${flourishBlock}
${blocks.PIXEL_ART_ONLY_BLOCK}

${blocks.NO_IP_REFERENCES_BLOCK}

${blocks.NORTH_STAR_BLOCK}

${blocks.NO_UI_BLOCK}

${blocks.ANIMATED_FEEL_BLOCK}

${blocks.BLOW_IT_UP_BLOCK}

━━━ MOOD ━━━
${vibeDirective.slice(0, 200)}

━━━ PALETTE ━━━
${sharedDNA.scenePalette}
${sharedDNA.colorPalette}

Output ONLY the 70-100 word Flux prompt, comma-separated. NO preamble, NO headers, NO ━━━ markers, NO "render as" suffixes. Start immediately with the scene description. End with: no text, no words, no letters, no watermarks, masterwork composition, hyper detailed.`;
};
