const blocks = require('../../pixelbot/shared-blocks');

const HOUSE_ARCHETYPES = require('../seeds/pixel_haunted_house_house.json');
const JACKOLANTERN_SWARM = require('../seeds/pixel_haunted_house_jackolanterns.json');
const YARD_GROUNDS = require('../seeds/pixel_haunted_house_yard.json');
const SKY_ATMOSPHERE = require('../seeds/pixel_haunted_house_sky.json');

// Short fixed lists — no generated-pool variety needed, per playbook guidance.
const BAT_FLIGHT_PATTERNS = [
  'a loose spiral of bats circling directly above the highest gable',
  'a ribbon of bats swooping low over the chimney in a wide arc',
  'a scattered V of bats crossing the sky just above the roofline',
  'a small flock of bats bursting upward from the eaves in a sudden flutter',
  'a thin trail of bats weaving between the bare treetops behind the house',
  'bats gliding in slow lazy loops around the highest tower or gable',
  'a cluster of bats perched along the roof ridge, wings half-spread, mid-launch',
];

const WINDOW_GLOW_DETAILS = [
  'one window glows warm amber with the friendly silhouette of a ghost mid-wave',
  'a black cat silhouette sits framed in a single lit windowsill',
  'a faint violet flicker glows behind one curtained window',
  'a string of small orange lights traces one porch window frame',
  'a single candle flickers in a small attic window',
  'a warm amber glow spills out through a door left just ajar',
  'a friendly spider silhouette dangles in the corner of one lit windowpane',
];

const COMPOSITION_FRAMES = [
  'a centered wide postcard framing, the house filling the middle-ground in full symmetrical presence, glowing pumpkins in the near-foreground leading the eye up toward it',
  'a gentle low hero angle looking up at the house looming just off-center, a foreground row of jack-o-lanterns anchoring the bottom edge',
  'a wide establishing view with the house centered and its grounds fanning out evenly to both sides',
  'a soft diagonal composition, the house set back and slightly left, a glowing path sweeping in from the lower-right corner',
  'a full symmetrical frontal view, the house dead-center like a storybook cover illustration',
  'a wide vista framing with the house slightly right-of-center and open twilight sky filling the left third',
];

module.exports = ({ sharedDNA, vibeDirective, picker }) => {
  const house = picker.pickWithRecency(HOUSE_ARCHETYPES, 'pixel_haunted_house_house');
  const swarm = picker.pickWithRecency(
    JACKOLANTERN_SWARM,
    'pixel_haunted_house_jackolanterns'
  );
  const yard = picker.pickWithRecency(YARD_GROUNDS, 'pixel_haunted_house_yard');
  const sky = picker.pickWithRecency(SKY_ATMOSPHERE, 'pixel_haunted_house_sky');
  const bats = picker.pickWithRecency(BAT_FLIGHT_PATTERNS, 'pixel_haunted_house_bats');
  const frame = picker.pickWithRecency(
    COMPOSITION_FRAMES,
    'pixel_haunted_house_composition'
  );

  // Window-glow flourish stays OPTIONAL (~50%) — per the hard-won lesson
  // that a signature detail mandatory on every entry homogenizes every
  // render into "the same one house."
  let windowBlock = '';
  if (Math.random() < 0.5) {
    const glow = picker.pickWithRecency(WINDOW_GLOW_DETAILS, 'pixel_haunted_house_window');
    windowBlock = `\n━━━ A WINDOW DETAIL (one small flourish) ━━━\n${glow}\n`;
  }

  return `You are a 16-bit pixel-art illustrator writing a PIXEL HAUNTED-HOUSE postcard scene for a Halloween candidate pixel-art bot path. NOT a gameplay screenshot, NOT a dungeon-crawl or side-scroller mimicry, NOT tied to any single in-game camera convention — this is a standalone, full atmospheric 16-bit pixel-art illustration, the kind of cozy-spooky Halloween postcard you'd frame. Family-friendly Halloween: charming and playful, never genuine horror, gore, or real scares.

━━━ THE HAUNTED HOUSE — NON-NEGOTIABLE TEMPLATE MANDATE ━━━
ONE spooky-but-charming house is the SINGULAR HERO of the frame. It is stacked all around with GLOWING carved jack-o-lanterns (this is the money shot — commit to it) and circled overhead by bats. The house is inviting and characterful, never derelict or menacing — a place you'd want to trick-or-treat at, not flee from.

━━━ THE HOUSE (LOCKED) ━━━
${house}

━━━ THE JACK-O-LANTERN SWARM — THE MONEY SHOT (glowing pumpkins stacked all around the house) ━━━
${swarm}

━━━ THE GROUNDS ━━━
${yard}

━━━ BATS OVERHEAD ━━━
${bats}
${windowBlock}
━━━ SKY + ATMOSPHERE ━━━
${sky}

━━━ COMPOSITION — POSTCARD FRAMING, NOT A GAMEPLAY CAMERA ━━━
${frame}

━━━ OPTICAL EFFECTS STAY PIXELATED (reflections, light beams, halos, glows) ━━━
This scene may include a water reflection, a moonbeam or light shaft through clouds, a hazy halo, or a glowing mist. Render EVERY one of those in the exact same chunky dithered pixel style as the house and pumpkins — hard-edged stepped pixel bands of color, NEVER a smooth photographic gradient, NEVER a soft airbrushed glow, NEVER a realistic mirror reflection. A moonbeam is a blocky dithered wedge of light, not a smooth column. A reflection is a rippled dithered mirror-image, not a glassy photographic one.

${blocks.PIXEL_ART_ONLY_BLOCK}

${blocks.NO_IP_REFERENCES_BLOCK}

${blocks.ANIMATED_FEEL_BLOCK}

${blocks.BLOW_IT_UP_BLOCK}

━━━ MOOD ━━━
${vibeDirective.slice(0, 200)}

━━━ PALETTE ━━━
${sharedDNA.scenePalette}
${sharedDNA.colorPalette}

Output ONLY the 70-100 word Flux prompt, comma-separated. NO preamble, NO headers, NO ━━━ markers, NO "render as" suffixes. Start immediately with the scene description. Do NOT close with "masterwork composition, hyper detailed" or any smooth-illustration/painterly closer — that vocabulary reads to the renderer as clean vector art or a polished digital painting and pulls the whole image away from chunky pixel-grid sprite craft (this is the #1 cause of renders drifting into smooth flat-illustration style instead of true 16-bit pixel art). Instead end with: no text, no words, no letters, no watermarks, true SNES-era pixel craft, chunky dithered pixel grid throughout, low effective sprite resolution.`;
};
