const blocks = require('../../pixelbot/shared-blocks');

const HAUNTED_REGION = require('../seeds/pixel_haunted_overworld_region.json');
const HAUNTED_LANDMARKS = require('../seeds/pixel_haunted_overworld_landmarks.json');
const JACKOLANTERN_TRAIL = require('../seeds/pixel_haunted_overworld_jackolantern_trail.json');
const SPIRIT_SPRITE = require('../seeds/pixel_haunted_overworld_spirit_sprite.json');
const GHOST_SPRITE = require('../seeds/pixel_haunted_overworld_ghost_sprite.json');

// Short fixed list — moon/fog/glow color-cast options. No generated-pool
// variety needed (it's a handful of lighting states, not concrete content).
const WITCHING_ATMOSPHERE = [
  'deep indigo-black tile-shadows washed with a warm harvest-orange moonglow over the whole map',
  'thin ribbons of pale fog drifting low across the tile-grid, softening the far edges',
  'a violet witching-hour haze tinting every tile with a faint purple cast',
  'scattered will-o-wisp glimmers hovering just above a handful of tiles',
  'a light drizzle of glowing orange embers drifting slowly across the dark tile-grid',
  'pale moonlight catching the edges of every tile cluster, deep shadow pooling between them',
  'a faint sickly-green witch-brew mist curling low along the ground tiles',
  'distant tile clusters fading softly into starlit darkness at the far edges of the map',
];

module.exports = ({ sharedDNA, vibeDirective, picker }) => {
  const region = picker.pickWithRecency(HAUNTED_REGION, 'pixel_haunted_overworld_region');

  // Always exactly 2 distinct landmark icons (mirrors PixelBot's own
  // pixel-overworld "render both" map_features mandate).
  const landmarks = [
    picker.pickWithRecency(HAUNTED_LANDMARKS, 'pixel_haunted_overworld_landmark'),
  ];
  let secondLandmark = picker.pickWithRecency(
    HAUNTED_LANDMARKS,
    'pixel_haunted_overworld_landmark'
  );
  for (let guard = 0; secondLandmark === landmarks[0] && guard < 5; guard++) {
    secondLandmark = picker.pickWithRecency(
      HAUNTED_LANDMARKS,
      'pixel_haunted_overworld_landmark'
    );
  }
  landmarks.push(secondLandmark);
  const landmarkBlock = landmarks.map((l, i) => `${i + 1}. ${l}`).join('\n');

  const trail = picker.pickWithRecency(
    JACKOLANTERN_TRAIL,
    'pixel_haunted_overworld_jackolantern_trail'
  );
  const sprite = picker.pickWithRecency(SPIRIT_SPRITE, 'pixel_haunted_overworld_spirit_sprite');
  const atmosphere = picker.pickWithRecency(
    WITCHING_ATMOSPHERE,
    'pixel_haunted_overworld_atmosphere'
  );

  // Ghost sprite stays OPTIONAL (~50%) — the money shot is the jack-o-lantern
  // trail; a second "dotting" beat on every single render would homogenize
  // and crowd the frame. Some maps glow with pumpkins alone; some also carry
  // a drifting ghost.
  let ghostBlock = '';
  if (Math.random() < 0.5) {
    const ghost = picker.pickWithRecency(GHOST_SPRITE, 'pixel_haunted_overworld_ghost_sprite');
    ghostBlock = `\n━━━ A GHOST SPRITE (optional second dotting beat) ━━━\n${ghost}\n`;
  }

  return `You are writing a 16-BIT RETRO PIXEL ART HAUNTED OVERWORLD MAP SCREEN for a Halloween candidate pixel-art bot path. The frame must read INSTANTLY as the overworld map screen of a classic 16-bit RPG's spooky Halloween region — a straight top-down view of a haunted tile-world you'd sail or walk across at night. Genre lineage: Final Fantasy / Dragon Quest / Chrono Trigger / Secret of Mana overworld maps, reskinned for a playful haunted-season chapter.

━━━ ABSOLUTE CAMERA + COMPOSITION LOCK (NON-NEGOTIABLE) ━━━
STRAIGHT TOP-DOWN WORLD-MAP VIEW — looking straight down at the tile-world from directly above, exactly like the overworld map SCREEN. The chunky repeating terrain TILE-GRID must read clearly.
🚫 NEVER a 3/4 town-view, NEVER a side-parallax landscape, NEVER a first-person view, NEVER a character portrait, NEVER a horizon or sky (this is looking straight DOWN at the map, not out at it).

━━━ MANDATORY ELEMENTS (every render) ━━━
1. THE HAUNTED REGION — the top-down haunted tile-geography filling the frame, chunky terrain tiles clearly readable, always night.
2. THE HAUNTED LANDMARKS — two small spooky landmark icons dotting the map.
3. THE JACK-O-LANTERN TRAIL — THE MONEY SHOT: glowing pixel jack-o-lanterns scattered/staged across the tiles (commit to this fully).
4. THE SPIRIT SPRITE — a TINY map-scale sprite crossing the tiles (never a portrait, never a close-up figure).

━━━ THE HAUNTED REGION (top-down tile geography, always night) ━━━
${region}

━━━ HAUNTED LANDMARKS (small icons dotting the map — render both) ━━━
${landmarkBlock}

━━━ THE JACK-O-LANTERN TRAIL — THE MONEY SHOT (glowing pumpkins dotting the tile map) ━━━
${trail}

━━━ THE SPIRIT SPRITE (tiny, map-scale, never a portrait) ━━━
${sprite}
${ghostBlock}
━━━ WITCHING-HOUR ATMOSPHERE ━━━
${atmosphere}

${blocks.PIXEL_ART_ONLY_BLOCK}

${blocks.NO_IP_REFERENCES_BLOCK}

${blocks.ANIMATED_FEEL_BLOCK}

━━━ FAMILY-FRIENDLY HALLOWEEN REGISTER ━━━
PLAYFUL, charming, whimsical spooky-cute Halloween only — grinning jack-o-lantern faces, friendly translucent ghosts, cartoonish bats. This is a Halloween you'd want to visit, never genuine horror, gore, or real scares.

━━━ HARD MANDATES (every render) ━━━
1. **PIXEL-ART REGISTER ONLY** — 16-bit / SNES-era. Chunky repeating terrain tiles, visible pixel grid. NEVER smooth illustration, NEVER 3D, NEVER photoreal.
2. **NO TEXT / UI / MENUS / MAP-LABELS / PLACE-NAMES / GRID-NUMBERS** — the map is pictorial only.
3. **NO IP REFERENCES** — no specific game maps, logos, or franchises.
4. **STRAIGHT TOP-DOWN MAP SCREEN** — looking straight down, tile-grid reads, no horizon/sky, no 3/4 view.
5. **GLOW = HARD-EDGED PIXEL LIGHT, NEVER SOFT BLOOM** — every jack-o-lantern/ghost/magic glow is a CHUNKY PIXELATED light-halo with visible dithered steps, like an SNES light-tile effect, not a smooth photographic bloom. NEVER describe a glow as "soft," "gentle," "pooling," "warmth," "shimmering," "luminous," "pastel," or "condensation" — those words are what pull Flux toward smooth painterly light instead of pixel art. Every light source reads as a stepped/dithered pixel-light effect only.

${blocks.BLOW_IT_UP_BLOCK}

━━━ MOOD ━━━
${vibeDirective.slice(0, 200)}

━━━ PALETTE ━━━
${sharedDNA.scenePalette}
${sharedDNA.colorPalette}

━━━ STRUCTURE — write in this exact order ━━━
[STRAIGHT top-down 16-bit pixel-art overworld map-screen, chunky visible tile-grid], [the haunted region's tile geography], [the two landmark icons], [the jack-o-lantern trail staging], [the tiny map-scale spirit sprite]${ghostBlock ? ', [the ghost sprite]' : ''}, [witching-hour atmosphere + palette]

The FIRST phrase you write must be that top-down pixel-art map-screen tag, before any atmosphere or scene language — this is what keeps the register and the camera locked. Do not open with mood or lighting description.

Output ONLY the 75-100 word Flux prompt, comma-separated phrases (not flowing prose sentences — short tags like the structure above). NO preamble, NO headers, NO ━━━ markers, NO "render as" suffixes. End with: no text, no words, no letters, no watermarks, masterwork composition, hyper detailed.`;
};
